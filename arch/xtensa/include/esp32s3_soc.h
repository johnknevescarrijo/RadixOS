/*
 * World Controller (WCL) Registers (Base: 0x600D0000, ESP32-S3 TRM)
 *
 * Offsets relative to DR_REG_WCL_BASE (Core 0: +0x0000, Core 1: +0x0400):
 *   +0x0000..+0x0030 : WCL_CORE_0_ENTRY_1..13_ADDR_REG
 *   +0x0080..+0x00B0 : WCL_CORE_0_STATUSTABLE1..13_REG (bit0: FROM_WORLD, bits[4:1]: FROM_ENTRY, bit5: CURRENT)
 *   +0x0140          : WCL_CORE_0_WORLD_TRIGGER_ADDR_REG
 *   +0x0144          : WCL_CORE_0_WORLD_PREPARE_REG (2'b01=World 0, 2'b10=World 1)
 *   +0x0148          : WCL_CORE_0_WORLD_UPDATE_REG (WO: write any value to commit)
 *   +0x014C          : WCL_CORE_0_WORLD_CANCEL_REG (WO: write any value to cancel pending switch)
 *   +0x0150          : WCL_CORE_0_WORLD_IRAM0_REG (bits[1:0]: current IRAM0 world)
 *   +0x0154          : WCL_CORE_0_WORLD_DRAM0_PIF_REG (bits[1:0]: current DRAM0/PIF world)
 *   +0x0158          : WCL_CORE_0_WORLD_PHASE_REG (bit0: preparing world switch)
 */
