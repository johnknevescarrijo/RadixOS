/*
 * PMS / Sensitive Registers (Base: 0x600C1000, ESP32-S3 TRM Permission Control)
 *
 * Split-line constrain registers (+0xC0..+0xD4):
 *   bits[13:0]  : 7 x 2-bit category descriptors (level 2..8):
 *                 0x0 = below split addr, 0x2 = contains split addr, 0x3 = above split addr
 *   bits[21:14] : 8-bit 256-byte-aligned split address within 64 KB SRAM level
 *
 * IRAM0 PMS constrain registers (+0xD8..+0xE0):
 *   World 1 (+0xDC), World 0 (+0xE0): 3-bit permission fields (R=BIT(0), W=BIT(1), X/F=BIT(2))
 *   bits[2:0] PMS_0, [5:3] PMS_1, [8:6] PMS_2, [11:9] PMS_3,
 *   bits[14:12] CACHEDATAARRAY_0, [17:15] CACHEDATAARRAY_1, [20:18] ROM_PMS
 *
 * DRAM0 PMS constrain registers (+0xFC..+0x100):
 *   World 0 & World 1 (+0x100): 2-bit permission fields (R=BIT(0), W=BIT(1))
 *   World 0: bits[1:0] PMS_0, [3:2] PMS_1, [5:4] PMS_2, [7:6] PMS_3, [9:8] CACHE_0, [11:10] CACHE_1
 *   World 1: bits[13:12] PMS_0, [15:14] PMS_1, [17:16] PMS_2, [19:18] PMS_3, [21:20] CACHE_0, [23:22] CACHE_1
 *   ROM    : bits[25:24] ROM_WORLD_0, [27:26] ROM_WORLD_1
 */
