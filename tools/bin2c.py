#!/usr/bin/env python3
"""
tools/bin2c.py - Convert a raw binary file into a C header byte array.

Used by RadixOS Makefile to embed compiled ULP RISC-V firmware (ulp_main.bin)
into drivers/ulp.c with compile-time size verification against RTC Slow RAM.
"""

import argparse
import os
import sys


def main() -> int:
    parser = argparse.ArgumentParser(description="Convert binary file to C array header.")
    parser.add_argument("input_bin", help="Input binary file path")
    parser.add_argument("output_h", help="Output C header path")
    parser.add_argument("--symbol", default="g_ulp_default_rv32imc_fw", help="C array symbol name")
    parser.add_argument("--max-size", type=lambda x: int(x, 0), default=0x1F00,
                        help="Maximum allowed binary size in bytes (default: 0x1F00)")
    args = parser.parse_args()

    with open(args.input_bin, "rb") as f:
        data = f.read()

    if len(data) == 0:
        print(f"Error: {args.input_bin} is empty", file=sys.stderr)
        return 1
    if len(data) > args.max_size:
        print(
            f"Error: {args.input_bin} ({len(data)} bytes) exceeds max size ({args.max_size} bytes)",
            file=sys.stderr,
        )
        return 1

    out_dir = os.path.dirname(args.output_h)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    lines = [
        "/* Auto-generated by tools/bin2c.py from compiled RISC-V ULP firmware. Do not edit. */",
        "#ifndef RADIX_ULP_FW_BIN_H",
        "#define RADIX_ULP_FW_BIN_H",
        "",
        "#include <radix/types.h>",
        "",
        f"static const uint8_t {args.symbol}[] __attribute__((aligned(4))) = {{",
    ]

    for i in range(0, len(data), 12):
        chunk = data[i : i + 12]
        hex_bytes = ", ".join(f"0x{b:02X}" for b in chunk)
        lines.append(f"    {hex_bytes},")

    lines.extend([
        "};",
        "",
        "#endif /* RADIX_ULP_FW_BIN_H */",
        "",
    ])

    with open(args.output_h, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"[BIN2C] {args.output_h}: {len(data)} bytes -> {args.symbol}[]")
    return 0


if __name__ == "__main__":
    sys.exit(main())
